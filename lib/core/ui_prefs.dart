/// 界面外观的运行时开关。
///
/// 放在 core 是因为读它的地方太杂：主题里的输入框兜底色、帖子页的玻璃底板、
/// 底栏、各种 Glass 控件都要看它一眼。这些组件不该反过来依赖 AppState
/// （那会把数据层和 UI 拧在一起），所以这里只留一个静态值，持久化仍由
/// [AppState] 负责，启动时同步进来。
library;

class UiPrefs {
  const UiPrefs._();

  /// 是否启用「液态玻璃」。
  ///
  /// 关掉后所有玻璃件退回不透明样式：不做背景模糊、底色用主题 surface、
  /// 描边用实色。开关本身是为了照顾不喜欢半透明、或者设备跑不动模糊的用户。
  static bool glass = true;
}
